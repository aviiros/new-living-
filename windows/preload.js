const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('liDesk', {
  translate: (id, text, src, tgt, online, hq, acc) => ipcRenderer.send('tr:go', id, text, src, tgt, !!online, !!hq, !!acc),
  prefs: () => ipcRenderer.sendSync('pref:get'),
  setPref: (k, v) => ipcRenderer.send('pref:set', String(k), v),
  onTr: (cb) => ipcRenderer.on('tr:ev', (_e, m) => cb(m)),
  schedule: (list) => ipcRenderer.send('ntf:schedule', list),
  cancel: (ids) => ipcRenderer.send('ntf:cancel', ids),
  fullscreen: () => ipcRenderer.invoke('win:fs'),
  printPdf: (html, name) => ipcRenderer.send('pdf:print', html, name),
  openUrl: (u) => ipcRenderer.send('open-url', u),
  ocrStatus: () => ipcRenderer.invoke('ai:ocr:status'),
  ocrPrep: () => ipcRenderer.invoke('ai:ocr:prep'),
  ocrPage: (img, lang) => ipcRenderer.invoke('ai:ocr:page', img, lang),
  ocrStop: () => ipcRenderer.invoke('ai:ocr:stop'),
  aiList: () => ipcRenderer.invoke('ai:list'),
  aiSelect: (k, id) => ipcRenderer.invoke('ai:select', k, id),
  aiAdd: (k) => ipcRenderer.invoke('ai:add', k),
  aiAddPP: () => ipcRenderer.invoke('ai:addpp'),
  aiRemove: (id) => ipcRenderer.invoke('ai:remove', id),
  aiState: () => ipcRenderer.invoke('ai:state'),
  aiSet: (p) => ipcRenderer.invoke('ai:set', p),
  aiUnload: () => ipcRenderer.invoke('ai:unload'),
  aiPause: (k) => ipcRenderer.invoke('ai:pause', k),
  aiResume: (k) => ipcRenderer.invoke('ai:resume', k),
  aiDl: (id) => ipcRenderer.invoke('ai:dl', id),
  aiDlPause: (id) => ipcRenderer.invoke('ai:dlpause', id),
  aiDlCancel: (id) => ipcRenderer.invoke('ai:dlcancel', id),
  aiVerify: (id) => ipcRenderer.invoke('ai:verify', id),
  onAiProg: (cb) => ipcRenderer.on('ai:prog', (_e, t) => cb(t))
});
